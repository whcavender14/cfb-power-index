# Generates src/site/usStates.ts: SVG outlines of the 50 states + DC for the recruiting maps (RecruitMap.tsx).
# Source: R `maps` package (public-domain US boundaries). Lower 48 in Albers conic; Alaska and Hawaii as insets.
suppressMessages(library(maps))
TOL <- 3.6
abbr <- c(setNames(state.abb, tolower(state.name)), "district of columbia" = "DC")
rad <- pi / 180
albers <- function(lon, lat, p1, p2, p0, l0) {
  n <- (sin(p1 * rad) + sin(p2 * rad)) / 2
  C <- cos(p1 * rad)^2 + 2 * n * sin(p1 * rad)
  rho <- function(phi) sqrt(C - 2 * n * sin(phi * rad)) / n
  th <- n * (lon - l0) * rad
  cbind(x = rho(lat) * sin(th), y = -(rho(p0) - rho(lat) * cos(th)))
}
polys <- function(m, keep) {  # split a fill=TRUE map into polygons, grouped by `keep(name)` -> state code
  na <- which(is.na(m$x)); st <- c(0, na); en <- c(na, length(m$x) + 1)
  out <- list()
  for (i in seq_along(m$names)) {
    code <- keep(m$names[i]); if (is.na(code)) next
    idx <- (st[i] + 1):(en[i] - 1)
    out[[code]] <- c(out[[code]], list(cbind(lon = m$x[idx], lat = m$y[idx])))
  }
  out
}
area <- function(p) abs(sum(p[, 1] * c(p[-1, 2], p[1, 2]) - c(p[-1, 1], p[1, 1]) * p[, 2])) / 2
s <- map("state", plot = FALSE, fill = TRUE)
lower <- polys(s, function(n) unname(abbr[sub(":.*", "", n)]))
w <- map("world", plot = FALSE, fill = TRUE)
ak <- polys(w, function(n) if (grepl("^USA:Alaska", n)) "AK" else NA_character_)
hi <- polys(w, function(n) if (grepl("^USA:Hawaii", n)) "HI" else NA_character_)
proj <- function(L, f) lapply(L, function(ps) lapply(ps, function(p) f(p[, 1], p[, 2])))
P <- c(proj(lower, function(a, b) albers(a, b, 29.5, 45.5, 37.5, -96)),
       proj(ak, function(a, b) { a <- ifelse(a > 0, a - 360, a); albers(a, b, 55, 65, 50, -154) }),
       proj(hi, function(a, b) albers(a, b, 8, 18, 3, -157)))
# Drop slivers (tiny islands) and Alaska's far Aleutian tail, then place the insets.
P <- lapply(P, function(ps) { A <- sapply(ps, area); ps[A > max(A) * 0.002] })
bb <- function(ps) { a <- do.call(rbind, ps); c(min(a[, 1]), max(a[, 1]), min(a[, 2]), max(a[, 2])) }
low <- bb(unlist(P[names(lower)], recursive = FALSE))
place <- function(ps, sc, ox, oy) { b <- bb(ps); lapply(ps, function(p) cbind((p[, 1] - b[1]) * sc + ox, (p[, 2] - b[3]) * sc + oy)) }
W <- low[2] - low[1]; H <- low[4] - low[3]
bak <- bb(P$AK); bhi <- bb(P$HI)
akS <- 0.30 * H / (bak[4] - bak[3]) * 1.0
P$AK <- place(P$AK, akS, low[1] + 0.00 * W, low[4] - 0.16 * H)
P$HI <- place(P$HI, 0.9 * akS, low[1] + 0.27 * W, low[4] + 0.0 * H)
allb <- bb(unlist(P, recursive = FALSE)); pad <- 0.01 * W
sc <- 1000 / (allb[2] - allb[1])
tf <- function(p) cbind((p[, 1] - allb[1] + pad) * sc, (p[, 2] - allb[3] + pad) * sc)
thin <- function(q, tol) { keep <- 1L; for (i in 2:nrow(q)) if (sqrt(sum((q[i, ] - q[tail(keep, 1), ])^2)) >= tol) keep <- c(keep, i); q[keep, , drop = FALSE] }
# Integer coordinates + relative line segments keep the module small (gzip budget in scripts/check_budget.mjs).
dpath <- function(ps) paste(sapply(ps, function(p) { q <- round(thin(tf(p), TOL)); if (nrow(q) < 3) return("")
  q <- q[c(TRUE, rowSums(abs(diff(q))) > 0), , drop = FALSE]; if (nrow(q) < 3) return("")
  d <- diff(q); paste0("M", q[1, 1], " ", q[1, 2], "l", paste(sprintf("%d %d", d[, 1], d[, 2]), collapse = " "), "z") }), collapse = "")
# Label point = pole of inaccessibility of the largest polygon: the interior point farthest from every border, so the count
# sits visually centered even for Florida's panhandle or Louisiana's boot. `r` is that distance (room for the label).
pole <- function(q) {
  x1 <- q[, 1]; y1 <- q[, 2]; x2 <- c(x1[-1], x1[1]); y2 <- c(y1[-1], y1[1])
  score <- function(px, py) {
    ins <- rep(FALSE, length(px)); d <- rep(Inf, length(px))
    for (i in seq_along(x1)) {
      ins <- xor(ins, ((y1[i] > py) != (y2[i] > py)) & (px < (x2[i] - x1[i]) * (py - y1[i]) / (y2[i] - y1[i]) + x1[i]))
      dx <- x2[i] - x1[i]; dy <- y2[i] - y1[i]; L <- dx^2 + dy^2
      t <- if (L == 0) 0 else pmax(0, pmin(1, ((px - x1[i]) * dx + (py - y1[i]) * dy) / L))
      d <- pmin(d, sqrt((px - (x1[i] + t * dx))^2 + (py - (y1[i] + t * dy))^2))
    }
    ifelse(ins, d, -1)
  }
  best <- c(NA, NA, -1)
  rx <- range(x1); ry <- range(y1)
  for (pass in 1:3) {
    gx <- seq(rx[1], rx[2], length.out = 45); gy <- seq(ry[1], ry[2], length.out = 45)
    g <- expand.grid(x = gx, y = gy); sc <- score(g$x, g$y); k <- which.max(sc)
    if (sc[k] > best[3]) best <- c(g$x[k], g$y[k], sc[k])
    hx <- (rx[2] - rx[1]) / 10; hy <- (ry[2] - ry[1]) / 10
    rx <- c(best[1] - hx, best[1] + hx); ry <- c(best[2] - hy, best[2] + hy)
  }
  best
}
label <- function(ps) { big <- ps[[which.max(sapply(ps, area))]]; pole(tf(big)) }
vb <- c(0, 0, (allb[2] - allb[1] + 2 * pad) * sc, (allb[4] - allb[3] + 2 * pad) * sc)
codes <- sort(names(P))
lines <- c("// Generated by scripts/gen_state_paths.R from the R `maps` package. Do not edit by hand.",
  sprintf("export const US_VIEWBOX = '0 0 %.0f %.0f'", vb[3], vb[4]),
  "export const US_STATES: Record<string, { d: string; x: number; y: number; r: number }> = {",
  sapply(codes, function(k) { l <- label(P[[k]]); sprintf("  %s: { d: '%s', x: %.1f, y: %.1f, r: %.1f },", k, dpath(P[[k]]), l[1], l[2], l[3]) }), "}")
writeLines(lines, "src/site/usStates.ts")
cat(length(codes), "states;", file.size("src/site/usStates.ts"), "bytes; viewBox", vb, "\n")
